"""
Общая часть обучения и инференса классификатора намерений.

Здесь живёт построение признаков — единственное место, где Python и PHP обязаны
вести себя одинаково. Обучение идёт здесь, а предсказание в проде считает PHP
(App\\Helpers\\Ai\\IntentClassifier), и если правила разойдутся хотя бы пробелом,
модель начнёт видеть другие признаки и молча деградирует.

КОНТЕКСТ. Классификатор смотрит не только на текущее сообщение, но и на
последнюю реплику агента. Без этого фразы вроде «давай» неразрешимы в принципе:

    агент: «...предлагаю объединить карточки. Применить?»   → «давай» = изменить дашборд
    агент: «...за какой период вас интересует?»             → «давай» = продолжение разговора

Одно и то же слово, разные намерения. Модель, видящая только текущее сообщение,
здесь может лишь угадывать — сколько её ни обучай.

Признаки двух пространств не смешиваются: n-граммы сообщения помечаются «m:»,
n-граммы контекста — «c:». Иначе слово «выгрузи», сказанное агентом, выглядело
бы для модели так же, как просьба пользователя выгрузить данные.
"""

import re

# Метки. Порядок фиксирован: он же порядок строк в матрице весов при выгрузке.
LABELS = ["chat", "dashboard", "export"]

# Диапазон длин символьных n-грамм.
#
# Символьные, а не словесные: пользователи пишут «сохранит», «сохронить»,
# «захрани» — слово ломается опечаткой целиком, а куски «сохр», «охра»
# переживают её и остаются признаком.
NGRAM_MIN = 3
NGRAM_MAX = 5

# Сколько символов последней реплики агента берём в признаки.
#
# Берётся ПОСЛЕДНЕЕ ПРЕДЛОЖЕНИЕ ответа — именно там стоит предложение действия
# («Применить предложенное?») или уточняющий вопрос («За какой период?»).
#
# Ограничение жёсткое не из экономии. Признаков у n-грамм примерно втрое больше
# числа символов, а вектор документа нормируется по длине: контекст в 160
# символов против сообщения в 20 давал бы девять десятых длины вектора, и модель
# начинала отвечать по реплике агента, игнорируя пользователя. Проверено —
# точность на обычных командах падала с 0.98 до 0.96 именно из-за этого.
CONTEXT_CHARS = 80

# Разделитель сообщения и контекста внутри одного документа.
#
# Документ — строка, а не пара: cross_val_predict приводит выборку к массиву,
# и список кортежей превратился бы в двумерную матрицу вместо списка текстов.
SEPARATOR = "\x00"

# Вес признаков контекста относительно признаков сообщения.
#
# Реплика агента длиннее сообщения в разы, а значит и n-грамм даёт в разы
# больше. Без понижающего веса вектор короткого «не надо» на девять десятых
# состоит из слов агента, и модель отвечает по предложению, которое пользователь
# как раз отклонил. Проверено: «не надо» после предложения выгрузки уходило
# в export.
#
# Вес применяется к значениям tf-idf ДО L2-нормализации — и в Python, и в PHP.
CONTEXT_WEIGHT = 0.35

_WHITESPACE = re.compile(r"\s+")
_SENTENCE_END = re.compile(r"[.!?…]+")
_MARKDOWN = re.compile(r"[*_`#>\[\]()|-]+")


def normalize(text: str) -> str:
    """Приводит фразу к виду, в котором из неё нарезаются n-граммы.

    Правила намеренно простые — их предстоит повторить в PHP один в один:

    1. нижний регистр;
    2. «ё» → «е» (пользователи пишут и так, и так, для модели это один символ);
    3. любые пробельные подряд → один пробел, края обрезаются;
    4. строка обрамляется пробелами — так n-граммы на границах слов отличаются
       от таких же внутри слова, и «сохрани» в начале фразы весит иначе, чем
       в середине.
    """
    text = (text or "").lower().replace("ё", "е")
    text = _WHITESPACE.sub(" ", text).strip()

    return f" {text} "


def context_tail(answer: str, limit: int = CONTEXT_CHARS) -> str:
    """Последнее предложение реплики агента — то, что задаёт смысл короткого ответа.

    Из markdown-разметки смысла не извлечь, а n-грамм она даёт много, поэтому
    символы разметки вычищаются. Дальше берётся последнее непустое предложение:
    и предложение действия, и уточняющий вопрос стоят именно в конце ответа,
    а разбор данных выше по тексту только зашумляет признаки.
    """
    text = _MARKDOWN.sub(" ", answer or "")
    text = _WHITESPACE.sub(" ", text).strip()

    if not text:
        return ""

    sentences = [part.strip() for part in _SENTENCE_END.split(text) if part.strip()]

    if sentences:
        text = sentences[-1]

    if len(text) <= limit:
        return text

    tail = text[-limit:]

    # Не начинаем с середины слова: обрезок «дить карточки» дал бы модели
    # n-граммы, которых в языке не бывает.
    space = tail.find(" ")

    return tail[space + 1:] if 0 <= space < 20 else tail


def char_ngrams(text: str, n_min: int = NGRAM_MIN, n_max: int = NGRAM_MAX):
    """Символьные n-граммы нормализованной строки.

    Реализовано вручную, а не через analyzer='char' в sklearn: PHP повторяет
    ровно этот цикл, и держать эталон в одном видимом месте надёжнее, чем
    надеяться, что чужая реализация не изменится с версией библиотеки.
    """
    chars = list(text)
    length = len(chars)

    for n in range(n_min, n_max + 1):
        for i in range(length - n + 1):
            yield "".join(chars[i:i + n])


def document(message: str, context: str = "") -> str:
    """Собирает обучающий документ из сообщения и контекста."""
    return f"{message or ''}{SEPARATOR}{context or ''}"


def features(message: str, context: str = ""):
    """Признаки: n-граммы сообщения и n-граммы контекста в разных пространствах.

    Префиксы «m:» и «c:» обязательны. Без них одна и та же последовательность
    символов из реплики агента и из сообщения пользователя попадала бы в один
    признак, и модель не смогла бы отличить «агент предложил выгрузку»
    от «пользователь просит выгрузку».
    """
    grams = ["m:" + gram for gram in char_ngrams(normalize(message))]

    tail = context_tail(context)

    if tail:
        grams += ["c:" + gram for gram in char_ngrams(normalize(tail))]

    return grams


def analyzer(raw: str):
    """Анализатор для TfidfVectorizer: разбирает документ и строит признаки."""
    message, _, context = (raw or "").partition(SEPARATOR)

    return features(message, context)
