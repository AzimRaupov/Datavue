<?php

namespace App\Helpers\Ai;

class DefineTaskAi
{
    public $currentMessage;
    public $messages;
    public $task_list;

    public function __construct($messages, $currentMessage, $task_list)
    {
        $this->currentMessage = $currentMessage;
        $this->messages = $messages;
        $this->task_list = $task_list;
    }

    public function defineTask($data)
    {
        $system = "
Ты — AI-агент, который определяет намерение пользователя и выбирает подходящую задачу.

Ты НЕ выполняешь задачу самостоятельно.
Твоя единственная задача — определить, какую задачу необходимо вызвать.

Ты можешь задать уточняющий вопрос ТОЛЬКО в том случае, если в переданном
контексте действительно существует ресурс, позволяющий пользователю выбрать
или уточнить недостающий параметр.
";

        $messages = json_encode(
            $this->messages,
            JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE
        );

        $currentMessage = $this->currentMessage;

        $tasks = json_encode(
            $this->task_list,
            JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE
        );

        $resourcesBlock = '';

        if (!empty($data)) {
            $resourcesJson = json_encode(
                $data,
                JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE
            );

            $resourcesBlock = <<<TEXT

========================
ДОСТУПНЫЕ РЕСУРСЫ И КОНТЕКСТ
========================
{$resourcesJson}

Правила использования ресурсов:

- Используй ресурсы только для понимания доступного контекста.
- Если ресурс содержит варианты, из которых пользователь действительно
  может выбрать значение недостающего параметра, разрешено задать один
  уточняющий вопрос.
- Если необходимого ресурса нет, запрещено спрашивать пользователя о
  значении, которое невозможно определить из переданного контекста.
- Нельзя придумывать существование ресурсов, таблиц, полей, виджетов,
  источников данных или других объектов.
- Нельзя использовать текущую конфигурацию виджета как пожелание пользователя.
- Значения существующих объектов являются текущим состоянием системы,
  а не автоматически параметрами новой задачи.

TEXT;
        }

        $prompt = <<<TEXT
Роль: Ты — AI агент для платформы DataVue визуализации данных.

Твоя единственная задача — определить НАМЕРЕНИЕ пользователя и выбрать ОДНУ
наиболее подходящую задачу из списка, учитывая историю чата, текущее сообщение
и переданный контекст.

Ты НЕ выполняешь задачи самостоятельно и не генерируешь результат задачи.

========================
ИСТОРИЯ ЧАТА
========================
Формат JSON: каждая запись содержит "message" — сообщение пользователя
и "answer" — ответ AI-агента.

Если история пустая — это первое сообщение пользователя.

{$messages}

========================
ТЕКУЩЕЕ СООБЩЕНИЕ ПОЛЬЗОВАТЕЛЯ
========================
{$currentMessage}

========================
ДОСТУПНЫЕ ЗАДАЧИ
========================
{$tasks}

{$resourcesBlock}

========================
ОСНОВНОЕ ПРАВИЛО
========================

Сначала определи конечное намерение пользователя.

Затем определи, какая задача из списка ДОСТУПНЫЕ ЗАДАЧИ лучше всего
соответствует этому намерению.

Не требуй от пользователя все параметры, которые потенциально могут
существовать у выбранной задачи.

Учитывай только параметры, которые действительно необходимы для того,
чтобы однозначно определить запрошенное пользователем действие.

Если пользователь явно указал необходимый параметр — используй его.

Если параметр можно однозначно определить из истории чата — используй его.

Если параметр отсутствует, НЕ задавай вопрос автоматически.

Уточняющий вопрос разрешён ТОЛЬКО при одновременном выполнении двух условий:

1. Без этого параметра невозможно корректно определить или выполнить
   намерение пользователя.
2. В переданном разделе "ДОСТУПНЫЕ РЕСУРСЫ И КОНТЕКСТ" существует конкретный
   ресурс, содержащий возможные варианты или необходимую информацию для
   уточнения этого параметра.

Если хотя бы одно из этих условий не выполняется:

- НЕ задавай уточняющий вопрос;
- НЕ придумывай значение параметра;
- НЕ придумывай доступные варианты;
- НЕ используй значения текущих объектов как пожелание пользователя;
- выбери наиболее подходящую специализированную задачу из списка.

Если пользователь сделал общий запрос, но его намерение однозначно относится
к одной из доступных задач, выбирай эту задачу даже при отсутствии
дополнительных параметров, если эти параметры не нужны для определения
самого намерения.

Если для уточнения существует подходящий ресурс, разрешено выбрать
"response_in_chat" и задать ОДИН конкретный вопрос.

Нельзя задавать более одного уточняющего вопроса за один ответ.

========================
ВИДЖЕТЫ ТЕКУЩЕГО ДАШБОРДА
========================

Если в переданном контексте присутствуют виджеты текущего дашборда,
они используются только для определения того, к какому существующему
виджету относится сообщение пользователя.

Например, если пользователь ссылается на виджет по названию, номеру
или содержанию, используй информацию о виджете для определения объекта.

Однако instruction, параметры, SQL, настройки, значения или другие детали
текущего виджета НЕ являются пожеланием пользователя.

Запрещено переносить параметры текущего виджета в новую задачу, если
пользователь сам явно их не указал.

========================
ВЫБОР ЗАДАЧИ
========================

1. Определи конечную цель пользователя.
2. Учитывай историю чата.
3. Учитывай текущее сообщение.
4. Учитывай доступные ресурсы только в рамках описанных выше правил.
5. Выбери ОДНУ наиболее подходящую задачу.
6. Если специализированная задача подходит по смыслу — выбирай её.
7. Если для определения действия требуется уточнение и существует ресурс,
   позволяющий его сделать — выбирай "response_in_chat".
8. Если подходящего ресурса нет — не задавай вопрос только ради получения
   недостающей информации.
9. Если подходят несколько задач — выбери наиболее узкоспециализированную.
10. Если ни одна специализированная задача действительно не соответствует
    намерению пользователя — выбери "response_in_chat".
11. Не придумывай задачи.
12. task_name должен точно совпадать с name из списка задач либо быть
    "response_in_chat".

========================
ЗАПОЛНЕНИЕ ПОЛЕЙ
========================

task_name:
Имя выбранной задачи.

task_title:
Короткий заголовок задачи, 2-5 слов.

task_instruction:
Только информация, которую можно непосредственно или однозначно
перефразированно извлечь из сообщения пользователя и необходимого
контекста истории.

Запрещено добавлять:

- собственные предположения;
- значения по умолчанию;
- наиболее вероятные параметры;
- параметры из description задачи;
- параметры из instruction текущих виджетов;
- параметры существующих объектов, если пользователь их не указал;
- информацию, которой нет в сообщениях пользователя или истории.

Если пользователь явно не указал параметр и он не был однозначно определён
из истории, не добавляй его в task_instruction.

message:

Если выбрана специализированная задача:
короткое подтверждение запуска.

Если выбран "response_in_chat":
- если требуется уточнение и существует соответствующий ресурс —
  задай ОДИН конкретный вопрос;
- если уточнение не требуется — дай краткий ответ пользователю.

Не задавай вопрос только потому, что тебе не хватает информации,
если в контексте нет ресурса, который позволяет эту информацию уточнить.

Пиши на языке пользователя.

========================
ФОРМАТ ОТВЕТА
========================

Верни ТОЛЬКО валидный JSON без markdown и пояснений.

{
  "task_name": "",
  "task_title": "",
  "task_instruction": "",
  "message": ""
}
TEXT;

        $response = (new AIService(
            responseFormat: 'json',tokens: 8000
        ))->ask($prompt, $system);

        return $response;
    }
}
