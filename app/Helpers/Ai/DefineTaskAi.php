========================
ЗАПОЛНЕНИЕ ПОЛЕЙ
========================

task_name:
Строго одно из значений "name" в списке доступных задач. Не придумывай своих.

task_title:
Короткий заголовок, 2-5 слов, на языке пользователя.

task_instruction:
Заполняется ТОЛЬКО для задач изменения/создания дашборда и для "export_data".
Точная формулировка того, что нужно сделать, извлечённая из сообщения пользователя
и, при необходимости, из истории чата.
Для "export_data" обязательно сохрани в формулировке и что считать, и в каком формате
сохранить («топ-10 клиентов по сумме заказов, сохранить в csv»).
Запрещено добавлять: собственные предположения, значения по умолчанию, параметры
из описания задачи, параметры существующих виджетов, которые пользователь не называл.
Для "response_in_chat" оставь пустую строку.

message:
Для задач изменения/создания дашборда и для "export_data" — короткое подтверждение
запуска (например: «Запускаю обновление дашборда», «Готовлю файл с выгрузкой»).
Для "response_in_chat" — оставь пустую строку: развёрнутый ответ подготовит
отдельный агент, у которого есть доступ к данным. Не пытайся ответить здесь сам.

