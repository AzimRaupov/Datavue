## ОПИСАНИЕ ПОЛЕЙ СХЕМЫ

Каждая таблица — ключ верхнего уровня. Поля:

- `count_rows` — количество строк в таблице.
- `columns.<column>.{type,nullable,key,default}` — тип, признак NULL, тип ключа (PRI/UNI/MUL), значение по умолчанию.
- `relations.<column>.relation.{table,column,confidence,match_rate}` — на какую таблицу/колонку ссылается колонка, уверенность и процент совпадения значений.

ВАЖНО про `confidence`/`match_rate`: это результат автоматической эвристики, а не гарантия смысловой связи.
Если у связи `match_rate` близок к 0 — это, скорее всего, ложное совпадение по типу данных
(например, два независимых столбца типа `bigint unsigned`), а не реальный внешний ключ.
Не строй группу только на основании такой связи — в первую очередь ориентируйся на
название таблицы, названия колонок и здравый смысл о её бизнес-назначении.
Связь с `match_rate` ниже 50 используй только как слабую подсказку, не как решающий довод.

