### 2. Назначение таблицы

Например:

customers:
"Информация о клиентах"

orders:
"Заказы клиентов"

payments:
"Платежи клиентов"

### 3. Общие бизнес-процессы

Примеры групп:

- Продажи и заказы
- Клиенты
- Товары и каталог
- Сотрудники и организация
- Финансы
- Логистика
- Аналитика
- Справочные данные

Названия групп должны соответствовать реальному содержимому базы данных.

