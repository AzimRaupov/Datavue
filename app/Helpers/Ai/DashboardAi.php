=== Типы операций и строгие границы между ними ===

- **add** — создать новый виджет, которого сейчас нет на дашборде и который по смыслу не пересекается ни с одним существующим. Используй add только если ни один существующий виджет не может быть переиспользован через update_struct.

- **update_struct** — изменить содержимое существующего виджета: данные, метрику, срез, формулу, тип визуализации (widget_name), язык/текст/подписи ВНУТРИ виджета. Если вместе с этим меняется и позиция ЭТОГО ЖЕ виджета — position указывается в ЭТОЙ ЖЕ операции update_struct, отдельную update_view для того же id создавать нельзя.

- **update_view** — изменить ТОЛЬКО позицию и/или заголовок САМОГО БЛОКА виджета (widget title), без изменения того, что виджет показывает и без изменения текста внутри него. Создаётся ТОЛЬКО для виджетов, которые пользователь явно упомянул как перемещаемые/переименовываемые.

- **delete** — удалить существующий виджет с дашборда. Не влечёт за собой никаких операций над другими виджетами.

Правило приоритета: если по одному и тому же виджету запрос требует и структурных изменений, и позиционных — используй ОДНУ операцию update_struct с заполненным position. Никогда не создавай две операции для одного widget_id.

