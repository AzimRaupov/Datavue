<?php

namespace App\Helpers\Ai;

class DashboardAi
{
    public function generateWidgets($tables, $widgets, $text)
    {
        $prompt = <<<TEXT

### 1. СПИСОК ДОСТУПНЫХ ТАБЛИЦ:
$tables

### 2. СПИСОК ДОСТУПНЫХ ТИПОВ ВИДЖЕТОВ (Используй ТОЛЬКО 'name' из этого списка):
$widgets

### 3. ЗАПРОС ПОЛЬЗОВАТЕЛЯ (ГЛАВНЫЙ ПРИОРИТЕТ):
"{$text}"

---

### ЗАДАЧА:
Сформируй полноценную, профессиональную структуру аналитического дашборда, которая максимально точно отвечает запросу пользователя.

---

## ❗ КРИТИЧЕСКИЕ ПРАВИЛА (ОБЯЗАТЕЛЬНО К СОБЛЮДЕНИЮ):

### 1. ЗАПРЕТ НА ВЫДУМЫВАНИЕ ПОЛЕЙ СХЕМЫ:
- Используй ТОЛЬКО поля, которые реально существуют в списке таблиц.
- НЕЛЬЗЯ придумывать новые названия колонок, метрик или атрибутов.
- Если нужного поля нет в схеме — НЕ ИЗОБРЕТАЙ ЕГО, а адаптируй логику под доступные данные.

---

### 2. ПРАВИЛА ДЛЯ "instruction":
- "instruction" — это ТОЛЬКО описание визуального вида и логики построения виджета.
- ЗАПРЕЩЕНО перечислять или выдумывать названия полей внутри instruction.
- Можно ссылаться только на уже существующие поля из схемы (без изменения их названий).
- Описывай:
  - тип визуализации (график, столбцы, линии, KPI и т.д.)
  - что сравнивается
  - как группируются данные
  - какие фильтры или агрегации применяются
- НЕЛЬЗЯ: придумывать новые атрибуты, поля, ключи или структуры данных.

---

### 3. РАЗБИЕНИЕ НА ЛОГИЧЕСКИЕ ЧАСТИ:
Если запрос комплексный — разбивай на отдельные аналитические блоки.
Каждый блок = отдельный объект JSON.

---

### 4. РАЗНООБРАЗИЕ ВИДЖЕТОВ:
- Виджеты mini-cards используй для общих метрик.
- Размести первыми виджеты mini-cards.
- Используй разные графики для разных срезов.
- Не дублируй смысл виджетов.

---

### 5. УНИКАЛЬНОСТЬ:
- Каждый "title" должен быть уникальным.
- Каждый объект должен отражать отдельную бизнес-логику.
- Запрещено дублировать один и тот же смысл разными виджетами.

---

## 📦 ТРЕБОВАНИЯ К JSON:

1. Выводи ТОЛЬКО валидный JSON объект (НЕ массив, именно объект с ключами "dashboard_name" и "widgets").
2. Никакого markdown, текста или пояснений.
3. Ключи виджета строго: "name", "title", "instruction", "tables".
4. "name" — только из списка виджетов.
5. "tables" — только реально используемые таблицы из схемы.
6. "title" — короткий человекочитаемый заголовок.
7. "instruction" — строго визуальное описание без выдуманных полей.
8. "dashboard_name" — короткое человекочитаемое название дашборда (обязательный ключ верхнего уровня).

---

## 📐 ЭТАЛОННЫЙ ФОРМАТ (СТРОГО ТАКОЙ, БЕЗ ИСКЛЮЧЕНИЙ — ОБЪЕКТ, НЕ МАССИВ):
{
  "dashboard_name": "Название дашборда",
  "widgets": [
    {
      "name": "название_виджета_из_списка",
      "title": "Уникальный заголовок",
      "instruction": "Описание визуализации без выдуманных полей",
      "tables": []
    }
  ]
}
TEXT;
        return (new AIService(responseFormat: 'json'))->ask($prompt);
    }

    /**
     * Общая часть системного промпта для генерации ТОЛЬКО тела main().
     * Используется и для первичной генерации, и для регенерации/добавления виджетов,
     * чтобы весь код в системе имел одинаковый контракт с шаблоном CodeTemplater.
     */
    private function mainBodySystemPrompt(): string
    {
        return <<<TEXT
Ты — специализированный генератор Python-функций для аналитики данных.
Ты генерируешь ТОЛЬКО тело функции main(), которая будет вставлена в уже существующий файл.
Ты никогда не выводишь импорты, определение функции query(), функции json_default(), обёртки if __name__ == "__main__" и любой код кроме main().
TEXT;
    }

    private function mainBodyTechnicalRules(): string
    {
        return <<<TEXT
СТРОГИЕ ПРАВИЛА:
1. Функция query(sql, params=None) уже существует. Используй ТОЛЬКО её для обращений к данным.
2. ЗАПРЕЩЕНО: создавать своё подключение к БД, переопределять query(), писать import, писать if __name__ == "__main__".
3. Тебе ДОСТУПНЫ ТОЛЬКО: pandas (как pd), json, встроенные типы Python (str, int, float, dict, list). Больше ничего импортировать не нужно.
4. Используй только реально существующие таблицы и поля из "ДОСТУПНАЯ СХЕМА".

СООТВЕТСТВИЕ ТИПОВ:
- int(N), smallint(N) -> Python int
- decimal(N,M) -> Python Decimal (арифметика работает как с числом, но для деления/среднего сначала приведи к float(): float(x))
- varchar(N), text -> Python str
- date -> Python datetime.date
- Поля с nullable "YES" могут быть None — обязательно учитывай это перед арифметикой (например через pd.to_numeric(df['col'], errors='coerce') или df['col'].fillna(0))

ПРАВИЛА РАБОТЫ С ТИПАМИ В КОДЕ:
- Для сумм/средних по decimal-колонкам: сначала pd.to_numeric(df['col'], errors='coerce'), потом .sum() / .mean().
- Не сравнивай числовые колонки со строками ('' вместо 0 и т.п.).
- Если колонка используется в count() — не приводи её к float, оставляй int.
- ОБЯЗАТЕЛЬНО выводи результат так: print(json.dumps(result, ensure_ascii=False, default=json_default))
  Функция json_default уже существует в файле и умеет сериализовать Decimal, date/datetime и numpy-скаляры — НЕ пиши свой собственный сериализатор и не приводи эти типы к str()/float() вручную ради JSON, просто передавай их как есть и используй default=json_default.

ТЕХНИЧЕСКИЕ ПРАВИЛА:
- Никаких комментариев в коде.
- Никакого markdown.
- В ответе — ТОЛЬКО одна функция: def main(): ...
TEXT;
    }

    public function generateContentWidget($dashboard_widget, $tables_scheme, $type, $codeTemplate)
    {
        $system = $this->mainBodySystemPrompt();

        $tablesJson = json_encode($tables_scheme, JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT);

        $prompt = <<<TEXT
Напиши функцию main(), которая агрегирует данные и форматирует их в нужный JSON.

КОНТЕКСТ (уже существует в файле, НЕ ВЫВОДИ это в ответе):

$codeTemplate

{$this->mainBodyTechnicalRules()}

ДОСТУПНАЯ СХЕМА:
{$tablesJson}

ИНСТРУКЦИЯ ПО ТОМУ, КАК ДОЛЖНО БЫТЬ:
{$dashboard_widget->instruction}

ЦЕЛЕВАЯ JSON СХЕМА ВЫВОДА:
{$dashboard_widget->widget->scheme}

ОПИСАНИЕ ПОЛЕЙ JSON ВЫХОДА:
{$dashboard_widget->widget->scheme_description}
TEXT;
        $response = (new AIService(responseFormat: 'text', tokens: 8000))->ask($prompt, $system);

        $pythonCode = trim((string) $response['content']);
        $pythonCode = preg_replace('/^```(?:python)?\s*/i', '', $pythonCode);
        $pythonCode = preg_replace('/\s*```$/', '', $pythonCode);
        $pythonCode = trim($pythonCode);

        if (!preg_match('/^\s*def\s+main\s*\(\s*\)\s*:/', $pythonCode)) {
            preg_match('/def\s+main\s*\(\s*\)\s*:.*/s', $pythonCode, $m);
            $pythonCode = $m[0] ?? $pythonCode;
        }

        return $pythonCode;
    }

    public function defineChanges($widgetsJson, $tablesJson, $availableWidgetsJson, $instruction)
    {
        $system = "Ты AI агент аналитической платформы DataVue. Твоя задача — по запросу пользователя точно определить минимальный набор операций над дашбордом (add/update/move/delete), не создавая дублей и не теряя существующие виджеты, которые пользователь не просил менять.";

        $prompt = <<<PROMPT
Ты анализируешь запрос пользователя к дашборду DataVue.

Твоя задача — определить, какие изменения необходимо выполнить над существующим дашбордом, чтобы итоговый набор и порядок виджетов точно соответствовал запросу.

=== Текущие виджеты дашборда (в текущем порядке, поле position — их текущая позиция, нумерация с 0) ===
{$widgetsJson}

=== Все таблицы, доступные в базе данных ===
{$tablesJson}

=== Список доступных типов виджетов (используются в поле "widget_name") ===
{$availableWidgetsJson}

=== Запрос пользователя ===
"{$instruction}"

=== Допустимые типы операции ===
- add — создать новый виджет, которого сейчас нет на дашборде.
- update — изменить содержание/визуализацию/данные существующего виджета (виджет остаётся тем же по смыслу, но пересчитывается заново).
- move — переместить существующий виджет на новую позицию БЕЗ изменения его содержимого. Используй эту операцию, когда пользователь просит изменить только порядок/расположение/место виджетов на дашборде, ничего не меняя в их данных или визуализации.
- delete — удалить существующий виджет с дашборда.

=== Правила определения типа операции ===
1. Если пользователь просит изменить только порядок или расположение уже существующих виджетов (например "передвинь", "поставь первым", "поменяй местами", "должны быть в начале/в конце") — используй ТОЛЬКО "move" для этих виджетов. Никогда не используй "add" для перемещения — это создаст дубликат существующего виджета. Никогда не используй "update" для перемещения — это впустую пересоздаст контент виджета.
2. Используй "add" только тогда, когда на дашборде нет виджета, который бы уже показывал то, что просит пользователь.
3. Используй "update", когда существующий виджет нужно оставить (тот же смысл/место в дашборде), но изменить его данные, метрику, тип визуализации или формулировку.
4. Верни только те операции, которые реально требуются по запросу. Все остальные виджеты не упоминай вообще — они автоматически останутся на дашборде без изменений.

=== Правила по полям ===
5. Для "update", "move" и "delete" обязательно используй существующий id виджета из списка выше в поле widget_id.
6. Для "add" всегда указывай "widget_id": null.
7. Никогда не придумывай несуществующие widget_id — используй только те, что реально есть в списке текущих виджетов.
8. "widget_name" обязателен для "add" и должен быть строго одним из значений поля "name" в списке доступных типов виджетов. Для "update" указывай новый widget_name только если тип визуализации должен смениться, иначе оставь прежний. Для "delete" и "move" widget_name не нужен (null).
9. Каждый id существующего виджета должен участвовать не более чем в одной операции.
10. "instruction" заполняется только для "add" и "update" и должно описывать, как именно должен выглядеть виджет и что именно он показывает (без выдуманных полей схемы, без упоминания номера/позиции). Для "delete" и "move" instruction = null.
11. "title" обязателен для "add" и "update" — короткий, точный, человекочитаемый заголовок, который отражает реальное содержание виджета (конкретную метрику/срез данных), а не общие фразы вроде "Новый виджет" или "Виджет 1". Для "delete" и "move" title = null.
12. "tables" — только реально существующие и релевантные таблицы из схемы, нужен для "add" и "update". Для "delete" и "move" — пустой массив [].
13. "position" — целевая позиция виджета в ИТОГОВОМ дашборде после применения всех операций (нумерация с 0, учитывай как изменяемые/новые, так и все нетронутые виджеты вместе). Указывай "position" для "add", "update" и "move" всегда, исходя из смысла запроса (если порядок не важен — ставь позицию в конец списка). Для "delete" position = null.
14. Если ни один виджет не требует изменений — верни пустой массив [].

=== Формат ответа ===
Верни ТОЛЬКО валидный JSON-массив объектов, без текста и markdown до или после JSON.

[
  {
    "widget_id": 5,
    "operation_type": "update",
    "widget_name": "",
    "title": "Продажи по месяцам",
    "position": 2,
    "instruction": "Столбчатая диаграмма, сравнивающая объём продаж по месяцам",
    "tables": ["orders"]
  },
  {
    "widget_id": null,
    "operation_type": "add",
    "widget_name": "",
    "title": "Количество продаж по категориям",
    "position": 0,
    "instruction": "Карточки с количеством продаж в разрезе категорий товаров",
    "tables": ["orders", "products"]
  },
  {
    "widget_id": 3,
    "operation_type": "move",
    "widget_name": null,
    "title": null,
    "position": 1,
    "instruction": null,
    "tables": []
  },
  {
    "widget_id": 9,
    "operation_type": "delete",
    "widget_name": null,
    "title": null,
    "position": null,
    "instruction": null,
    "tables": []
  }
]
PROMPT;
        return (new AIService(
            responseFormat: 'json',
            tokens: 7000
        ))->ask($prompt, $system);
    }

    /**
     * ВАЖНО: как и generateContentWidget(), возвращает JSON {"python_code": "def main(): ..."} —
     * ТОЛЬКО тело main(), а не полный скрипт. Сборка полного файла (импорты + query() + main() + footer)
     * происходит в вызывающем коде через CodeTemplater::assembleScript(), чтобы у всех виджетов
     * (первичная генерация / update / add) был один и тот же контракт с шаблоном.
     *
     * $codeTemplate — тот же CodeTemplater::generateFullScript(), что использовался при первичной
     * генерации, чтобы регенерация не ломала контракт (query('sql'), сигнатура main()).
     */
    public function reGenerateWidget($widgetSchemaJson, $tablesSchemeJson, $currentWidgetJson, $instruction, $widget_name, $codeTemplate): ?array
    {
        $system = $this->mainBodySystemPrompt();

        $prompt = <<<PROMPT
Перепиши тело функции main() существующего виджета аналитической платформы DataVue под новые требования.

КОНТЕКСТ (уже существует в файле, НЕ ВЫВОДИ это в ответе):

{$codeTemplate}

{$this->mainBodyTechnicalRules()}

Целевая схема виджета (тип, формат вывода):
{$widgetSchemaJson}

Схема доступных таблиц, релевантных виджету:
{$tablesSchemeJson}

Текущий виджет дашборда (для контекста, что было раньше):
{$currentWidgetJson}

Что нужно изменить (инструкция):
{$instruction}

Итоговый вывод функции main() должен строго соответствовать целевой JSON схеме виджета "{$widget_name}".

Ответ строго валидный JSON-объект, без пояснений и markdown:
{"python_code": "def main():\\n    ..."}
PROMPT;

        return (new AIService(
            responseFormat: 'json',
            tokens: 8000,
        ))->ask($prompt, $system);
    }
