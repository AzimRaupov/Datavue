5. "operation" — строка, ОБЯЗАТЕЛЬНО одно из двух значений: "add" — если виджет взят из группы создания , "update" — если виджет взят из группы обновления.
6. "tables" — непустой массив строк; каждая строка — точный ключ верхнего уровня из СХЕМЫ ДОСТУПНЫХ ТАБЛИЦ.
