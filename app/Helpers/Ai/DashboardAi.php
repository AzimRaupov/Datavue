## ⚙️ КАК СФОРМИРОВАТЬ "instruction" ДЛЯ ВИДЖЕТОВ НА ОБНОВЛЕНИЕ

Финальная "instruction" — это результат СЛИЯНИЯ "old_instruction" и "description_update", а НЕ копия одного из них и НЕ описание того, ЧТО поменять.

Пиши "instruction" так, будто виджет создаётся с нуля: полное, законченное описание конечного результата — какие данные, из каких таблиц/колонок, с какими подписями и в каком виде отображаются. Категорически запрещено использовать в тексте инструкции слова и обороты вида "обновить", "изменить", "заменить на", "переименовать согласно", "исходя из описания выше" и т.п. — это язык технического задания на изменение, а не описание готового виджета.

Алгоритм:
1. Возьми "old_instruction" как базу — в ней уже описаны реальные таблицы, колонки и логика виджета.
2. Определи, что именно должно измениться согласно "description_update" (подписи, набор показателей, тип агрегации и т.п.).
3. Перепиши "instruction" ПОЛНОСТЬЮ, целиком, как готовое описание виджета: все элементы (в том числе те, что НЕ менялись) должны быть перечислены explicit, с конкретными таблицами/колонками/подписями/значениями. Ничего не должно остаться "как было" по умолчанию без явного перечисления.
4. Финальная "instruction" должна быть самодостаточной: человек, читающий ТОЛЬКО её (без "old_instruction" и "description_update"), должен полностью понимать, как реализовать виджет — без каких-либо ссылок на "изменения" или "старую версию".
5. Не пересказывай только "description_update" — если в нём не указана вся информация (например, названия таблиц/колонок или значения, которые не меняются), возьми её из "old_instruction" и распиши её ПОЛНОСТЬЮ в итоговом тексте.

