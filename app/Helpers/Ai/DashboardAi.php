    public function generateContentWidget($dashboard_widget, $tables_scheme, $type, $codeTemplate)
    {


        $prompts=$this->providerAi->generateWidgetCode($dashboard_widget,$tables_scheme,$dashboard_widget->instruction,$codeTemplate);

        $response = (new AIService(responseFormat: 'text', tokens: 8000))->ask($prompts["prompt"], $prompts["system"]);

        $pythonCode = trim((string) $response['content']);
        $pythonCode = preg_replace('/^```(?:python)?\s*/i', '', $pythonCode);
        $pythonCode = preg_replace('/\s*```$/', '', $pythonCode);
        $pythonCode = trim($pythonCode);

        if (!preg_match('/^\s*def\s+main\s*\(\s*\)\s*:/', $pythonCode)) {
            preg_match('/def\s+main\s*\(\s*\)\s*:.*/s', $pythonCode, $m);
            $pythonCode = $m[0] ?? $pythonCode;
        }

        return $pythonCode;
    }

