1. Выводи ТОЛЬКО валидный JSON-массив (НЕ объект). Никаких оборачивающих ключей вроде "dashboard_name" или "widgets" — только массив объектов, описанный ниже.
2. Никакого markdown, текста, пояснений или комментариев до/после JSON.
3. В массиве должен быть ровно один объект на каждый виджет из обеих групп (создание + обновление), без пропусков.
