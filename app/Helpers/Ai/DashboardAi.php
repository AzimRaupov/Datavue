8. Не обрывай текст инструкции — каждая "instruction" должна быть завершённым предложением/абзацем, а не оборванной фразой.
9. ЗАПРЕЩЕНО добавлять в "instruction" любые сведения, которых нет в исходных данных ("description" / "old_instruction" / "description_update" / схема таблиц):
   - никаких рекомендаций по расположению, вёрстке, сетке, порядку отображения, количеству элементов в строке и т.п., если это explicitly не указано в исходных данных;
   - никаких предположений о цвете, размере, стиле, анимации, иконках и другом визуальном оформлении, если это explicitly не указано в исходных данных;
   - никаких "рекомендуется", "лучше отображать", "желательно" и подобных советующих формулировок от себя — пиши только то, что подтверждено исходными данными, без домыслов;
