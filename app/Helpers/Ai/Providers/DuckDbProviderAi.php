<?php

namespace App\Helpers\Ai\Providers;

/**
 * Генерация python-кода виджета для DuckDB — файловые источники
 * (CSV, Excel, SQL-дамп, Google Таблицы разбираются именно в него).
 *
 * Текст промптов общий для всех SQL-источников и живёт в SqlProviderAi —
 * здесь остаются только отличия диалекта.
 */
class DuckDbProviderAi extends SqlProviderAi
{
    protected function dialectName(): string
    {
        return 'DuckDB';
    }

    protected function dialectRules(): string
    {
        return <<<TEXT
- Плейсхолдеры параметров в query() — ?.
- Идентификаторы цитируются двойными кавычками: "таблица"."колонка".
  Данные пришли из файла, поэтому имена колонок могут содержать пробелы,
  кириллицу и заглавные буквы — цитируй их всегда.
- Ограничение выборки — LIMIT n.
- Диалект близок к PostgreSQL: усечение периода — DATE_TRUNC('month', колонка),
  форматирование — strftime(колонка, '%Y-%m'), конкатенация строк — оператор ||.
- Оператор / всегда даёт дробное число, целочисленного деления не происходит;
  если нужно именно целое — используй //.
- Типы колонок определены автоматически при разборе файла и могут оказаться
  VARCHAR даже там, где по смыслу число или дата. Для арифметики приводи явно
  через TRY_CAST(колонка AS DOUBLE), для дат — TRY_CAST(колонка AS DATE):
  в отличие от CAST, TRY_CAST возвращает NULL вместо падения на «грязном»
  значении, а COALESCE поверх него даёт предсказуемый результат.
- Пустые ячейки файла читаются как NULL, а не как пустая строка.
- Доступны оконные функции и QUALIFY — фильтруй по ним вместо подзапросов,
  где это короче.
TEXT;
    }
}
