<?php

namespace App\Helpers\Ai\Providers;

class DuckDbProviderAi
{
    public function generateWidget($title, $scheme, $widgets)
    {

    }

    public function generateWidgetCode(
        $dashboard_widget,
        $tables_scheme,
        $instruction,
        $codeTemplate
    )
    {
        $system = <<<TEXT
Ты — специализированный генератор аналитических Python-функций для DuckDb.

Твоя задача — сгенерировать только одну функцию main(), которая будет вставлена в уже существующий Python-файл.

Используй только данные, функции и библиотеки, доступные в переданном runtime-контексте и схеме базы данных.

Не выдумывай отсутствующие таблицы, колонки или связи.

Ответ должен содержать только исполняемый код функции main() без Markdown, комментариев и объяснений.

Код должен соотвествовать инструкции это главный приоритет если там сказано то надо сделать.
TEXT;

        $prompt = <<<TEXT
Сгенерируй функцию:

def main():
    ...

━━━━━━━━━━━━━━━━━━━━━━━━━━━━
RUNTIME
━━━━━━━━━━━━━━━━━━━━━━━━━━━━

В существующем Python-файле уже доступны:

{$codeTemplate}

Функция query(sql_query, params=None) уже существует и используется для выполнения SQL-запросов в DuckDb.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━
СХЕМА БАЗЫ ДАННЫХ
━━━━━━━━━━━━━━━━━━━━━━━━━━━━

{$tables_scheme}

Каждая таблица является ключом верхнего уровня.

В таблице могут присутствовать:

- `count_rows` — количество строк в таблице;
- `columns` — список доступных колонок;
- `relations` — связи колонок с другими таблицами;
- `relations.<column>.relation.table` — связанная таблица;
- `relations.<column>.relation.column` — связанная колонка.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━
JSON-СХЕМА РЕЗУЛЬТАТА
━━━━━━━━━━━━━━━━━━━━━━━━━━━━

{$dashboard_widget->widget->scheme}

Описание схемы:

{$dashboard_widget->widget->scheme_description}

━━━━━━━━━━━━━━━━━━━━━━━━━━━━
ИНСТРУЦИЯ И ЗАДАЧА ВИДЖЕТА (Главный приоритет)
━━━━━━━━━━━━━━━━━━━━━━━━━━━━

{$instruction}

━━━━━━━━━━━━━━━━━━━━━━━━━━━━
ПРАВИЛА ГЕНЕРАЦИИ
━━━━━━━━━━━━━━━━━━━━━━━━━━━━

1. Получай данные только через query().

2. Выполняй фильтрацию, JOIN, агрегацию, группировку и сортировку в DuckDb SQL.

3. Получай только данные, необходимые для формирования результата.

4. Используй только существующие таблицы, колонки и связи из схемы.

5. Структура результата должна соответствовать JSON-схеме.

6. Для возможных NULL используй COALESCE(), если это необходимо для корректного результата.

7. Используй json_default, если он доступен в runtime-контексте.

8. Не создавай новое подключение к базе данных.

9. Не загружай полные таблицы в Python, если результат можно получить через SQL-агрегацию.

10. Должен соотвествоват инструкции это главный приоритет если там сказано то надо сделать.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━
ЗАПРЕЩЕНО
━━━━━━━━━━━━━━━━━━━━━━━━━━━━

- создавать дополнительные функции;
- создавать классы;
- использовать if __name__ == "__main__";
- добавлять комментарии;
- добавлять Markdown;
- добавлять объяснения;
- писать код вне main().

━━━━━━━━━━━━━━━━━━━━━━━━━━━━
ФОРМАТ ОТВЕТА
━━━━━━━━━━━━━━━━━━━━━━━━━━━━

Верни только одну полную функцию:

def main():
    ...

Последней операцией обязательно должно быть:

print(json.dumps(result, ensure_ascii=False, default=json_default))

stdout должен содержать только один JSON-объект.
TEXT;
        return [
            'system' => $system,
            'prompt' => $prompt,
        ];
    }

