<?php

namespace App\Helpers\Task;

use App\Helpers\Ai\AIService;
use App\Models\Task;

class DefineTask
{
    public $currentMessage;
    public $messages;

    public $tasks;

    public function __construct($messages, $currentMessage){
        $this->currentMessage = $currentMessage;
        $this->messages = $messages;
        $this->tasks = Task::query()->where('name','generate_dashboard')
            ->orWhere('name','response_in_chat')
            ->select('name','description')
            ->get();

    }
    public function defineTask()
    {
        $system = "
Ты — AI-агент платформы DataVue.

Твои задачи:
1. Определить намерение пользователя и выбрать ОДНУ подходящую задачу из списка доступных задач.
2. Сформировать короткое сообщение для пользователя в поле \"message\".

Ты НЕ выполняешь специализированные задачи самостоятельно (например, не строишь дашборд сам,
не считаешь данные и т.д.) — для этого система вызовет отдельный обработчик по task_name.

НО если ни одна специализированная задача не подходит (выбрана response_in_chat),
ты ОБЯЗАН сам ответить пользователю по существу в поле \"message\" — так же, как обычный
ассистент отвечает на вопрос или задаёт уточняющий вопрос. Это не 'выполнение задачи',
это часть твоей прямой обязанности — коммуникация с пользователем.

Всегда возвращай только валидный JSON без markdown и пояснений.
";

        $messages = json_encode($this->messages, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE);
        $currentMessage=$this->currentMessage;
        $tasks = json_encode($this->tasks, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE);

        $prompt = <<<TEXT
Роль: Ты — AI агент для платформы DataVue.

Твоя задача — определить НАМЕРЕНИЕ пользователя, выбрать ОДНУ наиболее подходящую задачу
из списка и сформировать корректный, содержательный ответ в поле "message".

Ты НЕ выполняешь специализированные задачи самостоятельно и не генерируешь их результат
(например, не строишь сам дашборд). Но если выбрана response_in_chat — ты САМ являешься
источником ответа пользователю, и обязан дать полноценный, полезный ответ или один
уточняющий вопрос, а не формальную отбивку.

========================
ИСТОРИЯ ЧАТА
========================
Формат json: каждая запись содержит "message" — сообщение от пользователя и "answer" — ответ ИИ-агента.

Если история пустая — это первое сообщение пользователя.

{$messages}

========================
ТЕКУЩЕЕ СООБЩЕНИЕ ПОЛЬЗОВАТЕЛЯ
========================
{$currentMessage}

========================
ДОСТУПНЫЕ ЗАДАЧИ
========================
{$tasks}

========================
ПРАВИЛА ВЫБОРА task_name
========================
1. Определи конечную цель пользователя с учётом истории чата и текущего сообщения.
2. Выбери ОДНУ наиболее подходящую задачу из списка ДОСТУПНЫЕ ЗАДАЧИ.
3. Если специализированная задача подходит по смыслу — выбирай её, а не response_in_chat.
4. Если подходят сразу несколько задач — выбери наиболее узкоспециализированную (более точно соответствующую цели пользователя).
5. Если ни одна задача не подходит, или сообщение пользователя неоднозначно/недостаточно данных — выбери response_in_chat.
6. Не придумывай задачи, которых нет в списке ДОСТУПНЫЕ ЗАДАЧИ. Значение task_name должно ТОЧНО совпадать с одним из name из списка, либо быть "response_in_chat".

========================
ЗАПОЛНЕНИЕ ПОЛЕЙ
========================
task_name
Имя выбранной задачи. Должно точно совпадать с полем name из списка задач.

task_title
Короткий заголовок (2-5 слов), понятный человеку, отражающий суть запроса.
- Для специализированной задачи: например, "Дашборд продаж за март".
- Для response_in_chat: например, "Ответ на вопрос" или "Уточнение запроса" —
  заголовок должен отражать характер общения, а не быть пустым/generic всегда одинаковым.

task_instruction
Только для специализированных задач. Должен содержать только то, что можно
процитировать или перефразировать из сообщения пользователя. Если какого-то
слова, детали или формата нет в сообщении пользователя — его не должно быть
и в task_instruction, независимо от того, что написано в description задачи.
Если выбрана response_in_chat — оставь это поле пустой строкой "".

message
Сообщение ДЛЯ ПОЛЬЗОВАТЕЛЯ. Пиши на языке пользователя.
- Если выбрана специализированная задача — короткое подтверждение, что запущено
  (например: "Строю дашборд по вашим данным...").
- Если выбрана response_in_chat — это ТВОЙ ПОЛНОЦЕННЫЙ ОТВЕТ пользователю:
  либо прямой, содержательный ответ по существу вопроса (используя контекст истории чата),
  либо, если данных недостаточно, — ОДИН конкретный уточняющий вопрос.
  Не пиши общие фразы типа "Хорошо, помогу" без содержания. Отвечай по делу, естественно,
  как обычный ассистент в диалоге.

========================
ПРИМЕРЫ ОТВЕТОВ
========================

Пример 1 — выбрана специализированная задача:
Сообщение пользователя: "Построй дашборд по продажам за март"
Ответ:
{
  "task_name": "generate_dashboard",
  "task_title": "Дашборд продаж за март",
  "task_instruction": "Построй дашборд по продажам за март",
  "message": "Строю дашборд по продажам за март..."
}

Пример 2 — response_in_chat, прямой содержательный ответ:
Сообщение пользователя: "Что такое DataVue?"
Ответ:
{
  "task_name": "response_in_chat",
  "task_title": "Ответ на вопрос",
  "task_instruction": "",
  "message": "DataVue — это платформа для аналитики и визуализации данных, которая позволяет строить дашборды и отчёты на основе ваших данных."
}

Пример 3 — response_in_chat, уточняющий вопрос из-за недостатка данных:
Сообщение пользователя: "Сделай отчёт"
Ответ:
{
  "task_name": "response_in_chat",
  "task_title": "Уточнение запроса",
  "task_instruction": "",
  "message": "По каким данным нужен отчёт — продажи, финансы, посещения или что-то другое?"
}

========================
ФОРМАТ ОТВЕТА
========================
Верни ТОЛЬКО валидный JSON-объект без markdown, без ```, без пояснений до или после, строго по структуре:

{
  "task_name": "",
  "task_title": "",
  "task_instruction": "",
  "message": ""
}
TEXT;
        $response = (new AIService(
            responseFormat: 'json'
        ))->ask($prompt,$system);

        return $response;
    }
}
