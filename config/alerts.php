<?php

return [

    /*
    |--------------------------------------------------------------------------
    | Алерты: проверки по расписанию
    |--------------------------------------------------------------------------
    |
    | Алерт — сохранённая проверка над источником рабочего пространства. Раз в
    | заданный интервал платформа выполняет её сама и, если условие выполнилось,
    | шлёт письмо. Здесь — все пределы этого механизма.
    |
    */

    /**
     * Как часто можно проверять. Минимум намеренно высокий: проверка ходит
     * в боевую базу клиента, и «раз в минуту» на тяжёлом запросе — это уже
     * нагрузка, а не наблюдение.
     */
    'min_interval_minutes' => (int) env('ALERT_MIN_INTERVAL', 15),

    /** Пресеты интервала в интерфейсе (минуты). */
    'intervals' => [15, 30, 60, 180, 360, 720, 1440],

    'default_interval_minutes' => 60,

    /**
     * Сколько ждём проверку. SQL идёт в базу клиента, Python вдобавок
     * поднимает интерпретатор — поэтому пределы разные.
     */
    'sql_timeout' => (int) env('ALERT_SQL_TIMEOUT', 60),
    'python_timeout' => (int) env('ALERT_PYTHON_TIMEOUT', 60),

    /**
     * Сколько строк забираем как образец: они попадают в письмо и в историю.
     * Проверка отвечает на вопрос «сработало ли», а не «покажи все данные», —
     * тянуть больше незачем, а в письме больше и не прочитают.
     */
    'sample_rows' => (int) env('ALERT_SAMPLE_ROWS', 20),

    /**
     * Пауза между повторными письмами, пока условие продолжает выполняться.
     * Без неё «остаток ниже нормы» превращается в 24 письма в сутки, и на
     * второй день их перестают читать вовсе.
     */
    'repeat_after_minutes' => (int) env('ALERT_REPEAT_AFTER', 1440),

    /** Не чаще этого сообщаем автору, что алерт сломан. */
    'error_cooldown_hours' => (int) env('ALERT_ERROR_COOLDOWN', 24),

    /**
     * После скольких ошибок подряд алерт выключается сам.
     *
     * Сломанный алерт хуже отсутствующего: он создаёт ощущение присмотра,
     * которого нет. Поэтому его не оставляют падать вечно — выключаем
     * и сообщаем автору письмом.
     */
    'disable_after_failures' => (int) env('ALERT_DISABLE_AFTER_FAILURES', 10),

    /** Сколько дней держим историю проверок. */
    'history_ttl_days' => (int) env('ALERT_HISTORY_TTL_DAYS', 90),

    /** Потолок алертов на компанию — защита от «заведу на каждую строчку». */
    'max_per_company' => (int) env('ALERT_MAX_PER_COMPANY', 100),

    /** Потолок получателей одного алерта. */
    'max_recipients' => (int) env('ALERT_MAX_RECIPIENTS', 20),

    /** Сколько алертов ставим в очередь за один запуск планировщика. */
    'dispatch_batch' => (int) env('ALERT_DISPATCH_BATCH', 200),

];
