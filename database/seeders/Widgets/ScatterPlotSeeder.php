<?php

namespace Database\Seeders\Widgets;

class ScatterPlotSeeder extends WidgetFamilySeeder
{
    protected function family(): array
    {
        return [
            'name' => 'scatter',
            'description' => 'Взаимосвязь двух числовых метрик по набору сущностей: есть ли зависимость между ценой и '
                .'спросом, площадью и выручкой, стажем и результатом. Берите, когда вопрос про корреляцию, выбросы или '
                .'кластеры, а не про величину одной метрики.',

            'scheme' => [
                'series' => [
                    ['name' => 'string', 'data' => [[10, 25], [12, 30]]],
                ],
            ],

            'scheme_description' => <<<TEXT
series — массив наборов точек. Для каждого элемента:
- name — название набора (строка), попадёт в легенду;
- data — массив точек, каждая точка это пара чисел [x, y].

Правила:
- x — значение первой метрики (горизонтальная ось), y — второй (вертикальная);
- обе величины числовые: диаграмма рассеяния по категориям смысла не имеет;
- несколько элементов series — способ раскрасить точки по группам
  (например по регионам), а не показать разные метрики;
- разумный объём — до нескольких сотен точек.
TEXT,
        ];
    }

    protected function types(): array
    {
        return [
            [
                'name' => 'scatter',
                'title' => 'Точки',
                'description' => 'Обычная диаграмма рассеяния: каждая точка — одна сущность в координатах двух метрик.',
                'options' => ['chartType' => 'scatter'],
                'is_default' => true,
            ],
            [
                'name' => 'bubble',
                'title' => 'Пузырьки',
                'description' => 'Размер точки кодирует третью метрику. Берите, когда к паре метрик есть осмысленный '
                    .'«вес» сущности: цена и спрос при размере пузырька по выручке. Без третьей метрики берите "scatter".',
                'options' => ['chartType' => 'bubble'],
                'scheme' => [
                    'series' => [
                        ['name' => 'string', 'data' => [[10, 25, 140], [12, 30, 90]]],
                    ],
                ],
                'scheme_description' => <<<TEXT
series — массив наборов точек. Для каждого элемента:
- name — название набора (строка);
- data — массив точек, каждая точка это тройка чисел [x, y, z].

Правила:
- x и y — координаты (две сравниваемые метрики), z — размер пузырька (третья метрика);
- z должен быть положительным; нулевой размер точку не покажет;
- z берётся из данных, а не назначается произвольно.
TEXT,
            ],
        ];
    }
}
